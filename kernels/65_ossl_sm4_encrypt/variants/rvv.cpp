static inline uint32_t rotl(uint32_t x, unsigned n) {
    return (x << n) | (x >> (32 - n));
}

static inline uint32_t load_be(const uint8_t *p) {
    return (uint32_t(p[0]) << 24) | (uint32_t(p[1]) << 16) |
           (uint32_t(p[2]) << 8) | uint32_t(p[3]);
}

static inline void store_be(uint32_t x, uint8_t *p) {
    p[0] = uint8_t(x >> 24);
    p[1] = uint8_t(x >> 16);
    p[2] = uint8_t(x >> 8);
    p[3] = uint8_t(x);
}

static inline uint32_t substitute(uint32_t x) {
    // e8m1 has at least 16 lanes on base RVV (VLEN >= 128): all four
    // independent S-box accesses in this round execute as one indexed load.
    const uint8_t indices[4] = {uint8_t(x >> 24), uint8_t(x >> 16),
                                uint8_t(x >> 8), uint8_t(x)};
    uint8_t values[4];
    constexpr std::size_t vl = 4;
    vuint8m1_t offsets = __riscv_vle8_v_u8m1(indices, vl);
    vuint8m1_t boxes = __riscv_vloxei8_v_u8m1(sm4_s, offsets, vl);
    __riscv_vse8_v_u8m1(values, boxes, vl);
    return load_be(values);
}

static inline uint32_t round_t(uint32_t x) {
    uint32_t t = substitute(x);
    return t ^ rotl(t, 2) ^ rotl(t, 10) ^ rotl(t, 18) ^ rotl(t, 24);
}

static inline uint32_t key_t(uint32_t x) {
    uint32_t t = substitute(x);
    return t ^ rotl(t, 13) ^ rotl(t, 23);
}

int ossl_sm4_set_key_rvv(const uint8_t *key, SM4_KEY *ks) {
    static const uint32_t fk[4] = {0xa3b1bac6, 0x56aa3350, 0x677d9197,
                                   0xb27022dc};
    static const uint32_t ck[32] = {
        0x00070E15, 0x1C232A31, 0x383F464D, 0x545B6269, 0x70777E85, 0x8C939AA1,
        0xA8AFB6BD, 0xC4CBD2D9, 0xE0E7EEF5, 0xFC030A11, 0x181F262D, 0x343B4249,
        0x50575E65, 0x6C737A81, 0x888F969D, 0xA4ABB2B9, 0xC0C7CED5, 0xDCE3EAF1,
        0xF8FF060D, 0x141B2229, 0x30373E45, 0x4C535A61, 0x686F767D, 0x848B9299,
        0xA0A7AEB5, 0xBCC3CAD1, 0xD8DFE6ED, 0xF4FB0209, 0x10171E25, 0x2C333A41,
        0x484F565D, 0x646B7279};
    uint32_t k[4];
    for (int j = 0; j < 4; ++j) k[j] = load_be(key + 4 * j) ^ fk[j];
    for (int i = 0; i < SM4_KEY_SCHEDULE; ++i) {
        int j = i & 3;
        k[j] ^= key_t(k[(j + 1) & 3] ^ k[(j + 2) & 3] ^
                      k[(j + 3) & 3] ^ ck[i]);
        ks->rk[i] = k[j];
    }
    return 1;
}

static void crypt(const uint8_t *in, uint8_t *out, const SM4_KEY *ks,
                  bool decrypt) {
    uint32_t b[4];
    for (int j = 0; j < 4; ++j) b[j] = load_be(in + 4 * j);
    for (int i = 0; i < SM4_KEY_SCHEDULE; ++i) {
        int j = i & 3;
        uint32_t rk = ks->rk[decrypt ? 31 - i : i];
        b[j] ^= round_t(b[(j + 1) & 3] ^ b[(j + 2) & 3] ^
                        b[(j + 3) & 3] ^ rk);
    }
    for (int j = 0; j < 4; ++j) store_be(b[3 - j], out + 4 * j);
}

void ossl_sm4_encrypt_rvv(const uint8_t *in, uint8_t *out, const SM4_KEY *ks) {
    crypt(in, out, ks, false);
}

void ossl_sm4_decrypt_rvv(const uint8_t *in, uint8_t *out, const SM4_KEY *ks) {
    crypt(in, out, ks, true);
}
