static error_code minify_scalar(const uint8_t *buf, size_t len, uint8_t *dst,
                                size_t &dst_len) noexcept {
    size_t i = 0, pos = 0;
    uint8_t quote = 0;
    uint8_t nonescape = 1;

    while (i < len) {
        unsigned char c = buf[i];
        uint8_t *meta = jump_table + 3 * c;

        quote = quote ^ (meta[0] & nonescape);
        dst[pos] = c;
        pos += meta[2] | quote;

        i += 1;
        nonescape = uint8_t(~nonescape) | (meta[1]);
    }
    dst_len = pos;

    return quote ? UNCLOSED_STRING : SUCCESS;
}

